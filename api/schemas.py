"""
Pydantic schemas and models for the Backend API.

Defines schemas for tasks, planning, permissions, execution results,
and application catalogue endpoints in alignment with TEAM_CONTRACTS.md.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Planning Schemas
# ---------------------------------------------------------------------------

class PlanRequest(BaseModel):
    """Request payload to plan a natural language command."""
    text: str = Field(min_length=1, max_length=1000)


class PlanStepModel(BaseModel):
    """Structured plan step generated by the AI planner."""
    step_id: int
    action: str
    target: str
    depends_on: List[int] = Field(default_factory=list)
    expected_outcome: str = ""


class PlanResponseModel(BaseModel):
    """Structured result returned by the planner."""
    intent: str
    status: str
    requires_clarification: bool = False
    clarification_question: Optional[str] = None
    message: str = ""
    steps: List[PlanStepModel] = Field(default_factory=list)


# ---------------------------------------------------------------------------
# Task Lifecycle Schemas
# ---------------------------------------------------------------------------

class TaskCreate(BaseModel):
    """Request to create a new task."""
    title: str = Field(min_length=1, max_length=200)
    description: str = ""
    command: Optional[str] = None
    auto_execute: bool = False


class TaskResponse(BaseModel):
    """Detailed task response representing the task state."""
    task_id: str
    title: str
    description: str = ""
    status: str
    command: Optional[str] = None
    intent: Optional[str] = None
    steps: List[PlanStepModel] = Field(default_factory=list)
    created_at: Optional[str] = None


class TaskStatusResponse(BaseModel):
    """Task status polling response."""
    task_id: str
    status: str
    requires_approval: bool = False
    message: Optional[str] = None


class TaskResultResponse(BaseModel):
    """Task execution result response with verification evidence."""
    task_id: str
    status: str
    result: Optional[Any] = None
    message: str
    error_code: Optional[str] = None
    verification: Optional[Dict[str, Any]] = None
    audit: Optional[Dict[str, Any]] = None
    duration_ms: Optional[int] = None


class TaskExecuteRequest(BaseModel):
    """Parameters for executing a pending task."""
    timeout_seconds: float = 10.0


class TaskApproveRequest(BaseModel):
    """Parameters for approving a task in requires_approval status."""
    approval_reference: Optional[str] = None
    timeout_seconds: float = 10.0


class CommandRunRequest(BaseModel):
    """One-shot command dispatch payload (plan -> evaluate -> execute)."""
    text: str = Field(min_length=1, max_length=1000)
    auto_approve: bool = False
    timeout_seconds: float = 10.0


# ---------------------------------------------------------------------------
# Application Catalogue Schemas
# ---------------------------------------------------------------------------

class AppCatalogueItem(BaseModel):
    """Application catalogue entry."""
    app_name: str
    app_id: str
    executable: str
    allowlisted: bool = False
