"""
Pydantic schemas and models for the Backend API.

Defines schemas for tasks, planning, permissions, execution results,
voice input, voice transcript, shared task submission, and progress tracking
in alignment with TEAM_CONTRACTS.md.
"""

from typing import Any, Dict, List, Literal, Optional
from api.app_catalogue import AppCatalogueItem  # re‑export for FastAPI imports
from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Structured Task States
# ---------------------------------------------------------------------------

TaskState = Literal[
    "listening",
    "processing",
    "understanding",
    "matching",
    "launching",
    "executing",
    "launched",
    "verifying",
    "failed",
    "requires_approval",
    "awaiting_approval",
    "waiting_approval",   # Alias accepted by API consumers; maps to requires_approval internally
    "timed_out",          # Alias for failed due to timeout; returned in result.error_code == ERR_TIMEOUT
    "cancelled",
    "pending",
    "running",
    "completed",
]


# ---------------------------------------------------------------------------
# Timeline & Progress Schemas
# ---------------------------------------------------------------------------

class TimelineEntry(BaseModel):
    """Single chronological progress entry in task lifecycle."""
    timestamp: str
    state: str
    message: str


class TaskProgressResponse(BaseModel):
    """Granular task execution progress response."""
    task_id: str
    status: str
    progress_percent: int
    current_stage: str
    timeline: List[TimelineEntry] = Field(default_factory=list)
    message: Optional[str] = None
    intent: Optional[str] = None
    selected_application: Optional[str] = None
    application_id: Optional[str] = None
    structured_request: Optional[Dict[str, Any]] = None


# ---------------------------------------------------------------------------
# Planning Schemas
# ---------------------------------------------------------------------------

class PlanRequest(BaseModel):
    """Request payload to plan a natural language command."""
    text: str = Field(min_length=1, max_length=1000)


class PlanStepModel(BaseModel):
    """Structured plan step generated by the AI planner."""
    step_id: int
    action: str
    target: str
    depends_on: List[int] = Field(default_factory=list)
    expected_outcome: str = ""


class PlanResponseModel(BaseModel):
    """Structured result returned by the planner."""
    intent: str
    status: str
    requires_clarification: bool = False
    clarification_question: Optional[str] = None
    message: str = ""
    steps: List[PlanStepModel] = Field(default_factory=list)


# ---------------------------------------------------------------------------
# Task Lifecycle Schemas
# ---------------------------------------------------------------------------

class TaskCreate(BaseModel):
    """Request to create a new task."""
    title: str = Field(min_length=1, max_length=200)
    description: str = ""
    command: Optional[str] = None
    auto_execute: bool = False


class TaskResponse(BaseModel):
    """Detailed task response representing the task state."""
    task_id: str
    title: str
    description: str = ""
    status: str
    command: Optional[str] = None
    intent: Optional[str] = None
    steps: List[PlanStepModel] = Field(default_factory=list)
    created_at: Optional[str] = None


class TaskStatusResponse(BaseModel):
    """Task status polling response."""
    task_id: str
    status: str
    requires_approval: bool = False
    message: Optional[str] = None




class AppCapability(BaseModel):
    """Returned by /catalogue/{app_id}/capabilities – lists the actions an
    adapter declares for the given app."""
    app_id: str = Field(..., description="Application identifier")
    capabilities: List[str] = Field(..., description="Supported action names")



class ApplicationInfo(BaseModel):
    """Schema representing a discovered Windows application."""
    application_id: str = Field(..., description="Stable identifier, e.g., lower‑cased name or product GUID")
    name: str = Field(..., description="Human readable name")
    category: Optional[str] = Field(None, description="One of the categories defined in the spec")
    publisher: Optional[str] = Field(None, description="Publisher name if known")
    version: Optional[str] = Field(None, description="Version string")
    install_location: Optional[str] = Field(None, description="Base install folder")
    executable_path: Optional[str] = Field(None, description="Full path to the executable or shortcut target")
    process_name: Optional[str] = Field(None, description="Typical process name (e.g., notepad.exe)")
    launch_method: Optional[str] = Field(None, description="How to launch: 'executable', 'shortcut', 'uri', 'store', etc.")
    installed: bool = Field(True, description="True if the app is detected as installed")
    discovery_status: Optional[str] = Field(None, description="Notes about discovery (e.g., 'shortcut broken')")

# Alias for backward compatibility
AppCatalogueItem = ApplicationInfo  # noqa: N801

class LaunchTestResult(BaseModel):
    """Result of a lightweight launch‑test for an application."""
    app_id: str = Field(..., description="Application identifier")
    status: str = Field(..., description="One of SUCCESS, FAILED, TIMEOUT, NOT_TESTED, NEEDS_USER_ACTION, UNSUPPORTED")
    details: Optional[str] = Field(None, description="Human readable details or error message")


class TaskResultResponse(BaseModel):
    """Task execution result response with verification evidence."""
    task_id: str
    status: str
    result: Optional[Any] = None
    message: Optional[str] = ""
    error_code: Optional[str] = None
    error_message: Optional[str] = None
    verification: Optional[Dict[str, Any]] = None
    audit: Optional[Dict[str, Any]] = None
    duration_ms: Optional[int] = None
    intent: Optional[str] = None
    selected_application: Optional[str] = None
    application_id: Optional[str] = None
    structured_request: Optional[Dict[str, Any]] = None
    completed_at: Optional[str] = None

# New schema for browser profiles
class BrowserProfile(BaseModel):
    """Simple model representing a browser user profile."""
    name: str = Field(..., description="Profile name, e.g., 'Default' or 'Profile 1'")
    path: str = Field(..., description="Filesystem path to the profile directory")

    """Task execution result response with verification evidence."""
    task_id: str
    status: str
    result: Optional[Any] = None
    message: Optional[str] = ""
    error_code: Optional[str] = None
    error_message: Optional[str] = None
    verification: Optional[Dict[str, Any]] = None
    audit: Optional[Dict[str, Any]] = None
    duration_ms: Optional[int] = None
    intent: Optional[str] = None
    selected_application: Optional[str] = None
    application_id: Optional[str] = None
    structured_request: Optional[Dict[str, Any]] = None
    completed_at: Optional[str] = None



class TaskExecuteRequest(BaseModel):
    """Parameters for executing a pending task."""
    timeout_seconds: float = 10.0


class TaskApproveRequest(BaseModel):
    """Parameters for approving a task in requires_approval status."""
    approval_reference: Optional[str] = None
    timeout_seconds: float = 10.0


class CommandRunRequest(BaseModel):
    """One-shot command dispatch payload (plan -> evaluate -> execute)."""
    text: str = Field(min_length=1, max_length=1000)
    auto_approve: bool = False
    timeout_seconds: float = 10.0


# ---------------------------------------------------------------------------
# Voice & Unified Submission Schemas
# ---------------------------------------------------------------------------

class VoiceInputRequest(BaseModel):
    """Payload for voice input API."""
    audio_data: Optional[str] = None  # Base64 or audio identifier
    format: str = "wav"
    sample_rate: int = 16000
    simulate_service_down: bool = False
    idempotency_key: Optional[str] = None
    auto_execute: bool = True
    timeout_seconds: float = 10.0


class VoiceInputResponse(BaseModel):
    """Response returned upon accepting voice input."""
    task_id: str
    status: str
    message: str
    input_type: str = "voice"


class VoiceTranscriptRequest(BaseModel):
    """Payload for voice transcript API."""
    transcript: str = Field(min_length=1, max_length=1000)
    confidence: float = 1.0
    language: str = "en"
    auto_execute: bool = True
    idempotency_key: Optional[str] = None
    timeout_seconds: float = 10.0


class VoiceTranscriptResponse(BaseModel):
    """Response returned upon submitting voice transcript."""
    task_id: str
    status: str
    transcript: str
    message: str
    input_type: str = "voice"


class TaskSubmitRequest(BaseModel):
    """Unified task submission payload for text or voice commands."""
    command: str = Field(min_length=1, max_length=1000)
    input_type: Literal["text", "voice"] = "text"
    auto_execute: bool = True
    idempotency_key: Optional[str] = None
    timeout_seconds: float = 10.0


class StructuredActionRequest(BaseModel):
    """
    Structured action request representing a validated, normalized execution intent
    ready for dispatch to Windows Automation.
    """
    action: str = Field(min_length=1, description="Action to perform, e.g., 'launch_application'")
    application_id: str = Field(min_length=1, description="Canonical application identifier, e.g., 'chrome', 'vscode'")
    target: str = Field(min_length=1, description="Target application display name or executable")
    parameters: Dict[str, Any] = Field(default_factory=dict)
    source: Literal["text", "voice"] = "text"


class TaskSubmitResponse(BaseModel):
    """Response returned from unified task submission."""
    task_id: str
    input_type: str
    command: str
    status: str
    message: str
    intent: Optional[str] = None
    selected_application: Optional[str] = None
    application_id: Optional[str] = None
    structured_request: Optional[Dict[str, Any]] = None


class RefreshResponse(BaseModel):
    """Response model for catalogue refresh endpoint."""
    status: str = Field(..., description="Result status, e.g., 'ok' or 'error'")
    refreshed_at: str = Field(..., description="ISO timestamp of when the catalogue was refreshed")

